VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track", "wbr"}


class Scan(HTMLParser):
    """Collects links and ids, and checks that every element is closed in order."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.problems = []
        self.ids = []
        self.links = []
        self.headings = []
        self.text = []
        self.in_title = False
        self.title = ""
        self.doctype = False
        self.lang = None

    def handle_decl(self, decl):
        if decl.lower() == "doctype html":
            self.doctype = True

    def handle_starttag(self, tag, attrs):
        at = dict(attrs)
        line = self.getpos()[0]
        if tag == "html":
            self.lang = at.get("lang")
        if "id" in at:
            self.ids.append(at["id"])
        for k in ("href", "src"):
            if k in at:
                self.links.append((tag, k, at[k], line))
        if tag == "th" and not at.get("scope"):
            self.problems.append("line %d: <th> without scope" % line)
        if tag == "a" and "href" not in at:
            self.problems.append("line %d: <a> without href" % line)
        if re.match(r"^h[1-6]$", tag):
            self.headings.append((int(tag[1]), line))
        if tag == "title":
            self.in_title = True
        if tag not in VOID:
            self.stack.append((tag, line))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in VOID:
            self.stack.pop()

    def handle_endtag(self, tag):
        line = self.getpos()[0]
        if tag == "title":
            self.in_title = False
        if tag in VOID:
            self.problems.append("line %d: end tag </%s> for a void element" % (line, tag))
            return
        if not self.stack:
            self.problems.append("line %d: </%s> closes nothing" % (line, tag))
            return
        if self.stack[-1][0] == tag:
            self.stack.pop()
            return
        if tag in [x for x, _ in self.stack]:
            while self.stack[-1][0] != tag:
                x, ln = self.stack.pop()
                self.problems.append("line %d: <%s> not closed before </%s> at line %d" % (ln, x, tag, line))
            self.stack.pop()
        else:
            self.problems.append("line %d: </%s> does not match the open <%s>" % (line, tag, self.stack[-1][0]))

    def handle_data(self, data):
        if self.in_title:
            self.title += data
        self.text.append(data)

    def finish(self):
        self.close()
        for x, ln in self.stack:
            self.problems.append("line %d: <%s> never closed" % (ln, x))
        if not self.doctype:
            self.problems.append("no <!doctype html>")
        if not self.lang:
            self.problems.append("<html> has no lang")
        if not self.title.strip():
            self.problems.append("empty <title>")
        h1 = [h for h in self.headings if h[0] == 1]
        if len(h1) != 1:
            self.problems.append("%d <h1> elements" % len(h1))
        prev = 0
        for lvl, ln in self.headings:
            if lvl > prev + 1:
                self.problems.append("line %d: heading h%d follows h%d" % (ln, lvl, prev))
            prev = lvl
        dup = sorted({i for i in self.ids if self.ids.count(i) > 1})
        if dup:
            self.problems.append("duplicate ids: %s" % ", ".join(dup))
        return self


def scan_html(text):
    s = Scan()
    s.feed(text)
    return s.finish()


LEAK_RE = re.compile(r"\b(None|null|undefined|NaN|OWNER|TODO)\b|\{[a-z_:]+\}")
BAD_SEGMENTS = {"none", "null", "undefined", "owner", "nan"}


def check_external(href, allowed, problems, where, stats, owner, repo, branch, repo_links):
    """An absolute link: well formed, with a scheme and host the config names."""
    p = urlsplit(href)
    if p.scheme not in ("https", "http"):
        problems.append("%s: scheme %r: %s" % (where, p.scheme, href))
        return
    if not p.hostname or p.port is not None or p.username or p.netloc != p.hostname:
        problems.append("%s: malformed or upper-case host: %s" % (where, href))
        return
    if p.hostname not in allowed:
        problems.append("%s: host %s is not one the config names: %s" % (where, p.hostname, href))
        return
    if p.scheme not in allowed[p.hostname]:
        problems.append("%s: %s link where the config says %s: %s"
                        % (where, p.scheme, "/".join(sorted(allowed[p.hostname])), href))
    segs = [s.lower() for s in p.path.split("/") if s]
    if any(s in BAD_SEGMENTS for s in segs) or "{" in href or "}" in href or "%7b" in href.lower():
        problems.append("%s: placeholder in URL: %s" % (where, href))
    if "//" in p.path:
        problems.append("%s: empty path segment: %s" % (where, href))
    stats[p.hostname] = stats.get(p.hostname, 0) + 1
    if p.hostname == "github.com":
        m = re.match(r"^/%s/%s(?:\.git|/(?:blob|tree)/%s/(.+))?$"
                     % (re.escape(owner or ""), re.escape(repo), re.escape(branch)), p.path)
        if not m:
            problems.append("%s: GitHub link outside the repository: %s" % (where, href))
        elif m.group(1):
            repo_links.add(m.group(1))


def canonical(cfg):
    """The four top-line links, spelled out here a second time and on purpose not
    through the Links class, so that a change in Links cannot pass the check unseen.
    The Data link is the folder the paper cites, not the v1/ subfolder. None where
    the config value is null."""
    owner, repo = cfg["github_owner"], cfg["repo_name"]
    return {
        "repository": "https://github.com/" + owner + "/" + repo if owner else None,
        "website": "https://" + owner.lower() + ".github.io/" + repo + "/" if owner else None,
        "data": cfg["data_folder_url"],
        "paper": "https://arxiv.org/abs/" + cfg["arxiv_id"] if cfg["arxiv_id"] else None,
    }


def check_form(href, cfg, canon, data_files, problems, where, text_url):
    """Every absolute link must have one of the exact forms the site is allowed to print."""
    ok = (href == text_url
          or (canon["paper"] and href == canon["paper"])
          or href == "https://arxiv.org/abs/" + cfg["table_paper"]["arxiv_id"]
          or (cfg["doi"] and href == "https://doi.org/" + quote(cfg["doi"], safe="/:;._-"))
          or any(cfg[k] and href == LICENCES[cfg[k]][1] for k in ("code_licence", "data_licence")))
    r = canon["repository"]
    if not ok and r:
        ok = (href == r or href == r + ".git"
              or re.match(r"^%s/(blob|tree)/%s/[A-Za-z0-9._/-]+$" % (re.escape(r), re.escape(cfg["branch"])), href))
    w = canon["website"]
    if not ok and w:
        ok = href == w or re.match(r"^%s(?:[a-z0-9_/-]+\.html)?(?:#[A-Za-z0-9_-]+)?$" % re.escape(w), href)
    folder, base = canon["data"], cfg["data_base_url"]
    if not ok and folder:
        ok = href == folder
    if not ok and base and href.startswith(base + "/"):
        name = href[len(base) + 1:]
        ok = name == "" or (name in data_files if data_files else bool(re.match(r"^[A-Za-z0-9._-]+$", name)))
    if not ok:
        problems.append("%s: not one of the canonical link forms: %s" % (where, href))


def readme_block_links(md):
    return [m.group(1) for m in re.finditer(r"\]\(([^)]*)\)", md)]


def check_site(out_dir, cfg, text_url, readme_path=None, repo_root=None, named_paths=(), data_files=(),
               readme_full=None):
    """Check every generated page and the README block. Returns (problems, report)."""
    L = Links(cfg, text_url)
    allowed = L.allowed()
    canon = canonical(cfg)
    data_files = set(data_files)
    problems = []
    stats = {}
    repo_links = set()
    scans = {}
    for path in sorted(out_dir.rglob("*.html")):
        rel = path.relative_to(out_dir).as_posix()
        s = scan_html(path.read_text(encoding="utf-8"))
        scans[rel] = s
        problems += ["%s: %s" % (rel, m) for m in s.problems]
        leak = LEAK_RE.search(" ".join(s.text))
        if leak:
            problems.append("%s: placeholder text %r in the page" % (rel, leak.group(0)))
    nlocal = nexternal = 0
    for rel, s in scans.items():
        for tag, attr, href, line in s.links:
            where = "%s:%d <%s %s>" % (rel, line, tag, attr)
            if href is None or not href.strip():
                problems.append("%s: empty link" % where)
                continue
            if href != href.strip() or re.search(r"\s", href):
                problems.append("%s: whitespace in link %r" % (where, href))
                continue
            p = urlsplit(href)
            if p.scheme or href.startswith("//"):
                nexternal += 1
                check_external(href, allowed, problems, where, stats, L.owner, L.repo, L.branch, repo_links)
                check_form(href, cfg, canon, data_files, problems, where, text_url)
                continue
            if href.startswith("/"):
                problems.append("%s: root-relative link breaks under the Pages path: %s" % (where, href))
                continue
            nlocal += 1
            if p.query:
                problems.append("%s: query in a local link: %s" % (where, href))
            target = os.path.normpath(os.path.join(os.path.dirname(rel), p.path or os.path.basename(rel))).replace("\\", "/")
            if p.path.endswith("/"):
                target = target + "/index.html"
            if target.startswith(".."):
                problems.append("%s: link leaves the site: %s" % (where, href))
                continue
            if not (out_dir / target).is_file():
                problems.append("%s: missing local page %s" % (where, target))
                continue
            if p.fragment:
                if target not in scans:
                    problems.append("%s: fragment on a file that is not a page: %s" % (where, href))
                elif p.fragment not in scans[target].ids:
                    problems.append("%s: no id %r in %s" % (where, p.fragment, target))
    nreadme = 0
    readme_links = set()
    if readme_path is not None and Path(readme_path).exists():
        md = Path(readme_path).read_text(encoding="utf-8")
        name = Path(readme_path).name
        for href in readme_block_links(md):
            nreadme += 1
            where = "%s link %d" % (name, nreadme)
            if not href or re.search(r"\s", href):
                problems.append("%s: empty or spaced link %r" % (where, href))
                continue
            p = urlsplit(href)
            if not p.scheme:
                problems.append("%s: relative link in the README block: %s" % (where, href))
                continue
            check_external(href, allowed, problems, where, stats, L.owner, L.repo, L.branch, repo_links)
            check_form(href, cfg, canon, data_files, problems, where, text_url)
            readme_links.add(href)
            if p.fragment and p.hostname and p.hostname.endswith(".github.io"):
                page = p.path.split("/", 2)[-1] or "index.html"
                if page in scans and p.fragment not in scans[page].ids:
                    problems.append("%s: no id %r in %s" % (where, p.fragment, page))
        leak = LEAK_RE.search(re.sub(r"<!--.*?-->", "", md, flags=re.S))
        if leak:
            problems.append("%s: placeholder text %r" % (name, leak.group(0)))
        if readme_full is not None and Path(readme_full).exists():
            full = Path(readme_full).read_text(encoding="utf-8")
            i, j = full.find(LINKS_START), full.find(LINKS_END)
            if i < 0 or j < i or full[i:j + len(LINKS_END)] + "\n" != md:
                problems.append("%s: its links block differs from %s (run make site)" % (Path(readme_full).name, name))
    # the top-line links: each known one must appear, exactly, on the front page and in the README
    front = {h for _, _, h, _ in scans["index.html"].links} if "index.html" in scans else set()
    have_readme = readme_path is not None and Path(readme_path).exists()
    for label, url in canon.items():
        if url is None:
            continue
        if url not in front:
            problems.append("index.html: the %s link %s is missing" % (label, url))
        if have_readme and url not in readme_links:
            problems.append("README block: the %s link %s is missing" % (label, url))
    named = set(named_paths) | repo_links
    report = ["pages: %d HTML files parsed (tags closed in order, one h1, no skipped heading level, "
              "th scope, unique ids, doctype, lang, title)" % len(scans),
              "links: %d local (every target page and #fragment exists), %d external, %d in the README block"
              % (nlocal, nexternal, nreadme),
              "external hosts the config allows: %s" % ", ".join(sorted(allowed)),
              "external links by host: %s" % (", ".join("%s %d" % kv for kv in sorted(stats.items())) or "none"),
              "top-line links (front page and README): %s"
              % "; ".join("%s %s" % (k, v if v else "(link at release)") for k, v in canon.items())]
    if repo_root is not None and looks_like_repo(repo_root):
        for path in sorted(named):
            if not (Path(repo_root) / path).exists():
                problems.append("repository path %s is missing in %s" % (path, repo_root))
        report.append("repository paths: %d named, each checked in the repository" % len(named))
    else:
        report.append("repository paths: %d named, not checked here (no Makefile and src/): %s"
                      % (len(named), ", ".join(sorted(named))))
    return problems, report


def check_data_folder(files, cfg, text_url, data_files, repo_sums):
    """The data folder files: page structure, links, and SHA256SUMS equal to the repository's."""
    problems = []
    L = Links(cfg, text_url)
    allowed = L.allowed()
    canon = canonical(cfg)
    present = {p.as_posix() for p in files}
    for rel, text in files.items():
        relp = rel.as_posix()
        if not relp.endswith(".html"):
            continue
        s = scan_html(text)
        problems += ["data folder %s: %s" % (relp, m) for m in s.problems]
        for tag, attr, href, line in s.links:
            where = "data folder %s:%d" % (relp, line)
            p = urlsplit(href)
            if p.scheme:
                check_external(href, allowed, problems, where, {}, L.owner, L.repo, L.branch, set())
                check_form(href, cfg, canon, data_files, problems, where, text_url)
                continue
            target = os.path.normpath(os.path.join(os.path.dirname(relp), p.path)).replace("\\", "/")
            if p.path.endswith("/"):
                target += "/index.html"
            if target.startswith(".."):
                problems.append("%s: link leaves the folder: %s" % (where, href))
            elif target not in present and os.path.basename(target) not in data_files:
                problems.append("%s: link to a file the folder does not hold: %s" % (where, href))
    sums = [t for p, t in files.items() if p.name == "SHA256SUMS"]
    if repo_sums is not None and sums and sums[0] != repo_sums:
        problems.append("data folder SHA256SUMS differs from the repository's SHA256SUMS (run make table)")
    return problems


def looks_like_repo(root):
    root = Path(root)
    return (root / "Makefile").is_file() and (root / "src").is_dir()


# ------------------------------------------------------------------ main

def main(argv=None):
    ap = argparse.ArgumentParser(description="Build the project website, the README links block and the data folder files.")
    ap.add_argument("--repo-root", type=Path, default=HERE.parent,
                    help="repository root (default: the parent of site/)")
    ap.add_argument("--config", type=Path, help="link config (default: site/site.json)")
    ap.add_argument("--cells", type=Path, help="prose (default: site/cells.json)")
    ap.add_argument("--out", type=Path, help="output directory (default: docs/)")
    ap.add_argument("--readme-out", type=Path, help="README links block (default: site/README_header.md)")
    ap.add_argument("--readme", type=Path, help="README to splice the block into (default: README.md; 'none' to skip)")
    ap.add_argument("--data-folder", type=Path, help="data folder output (default: dist/data-folder; 'none' to skip)")
    ap.add_argument("--check", action="store_true",
                    help="write nothing: report outputs that are out of date, then check the links")
    ap.add_argument("--check-only", action="store_true", help="the same as --check")
    args = ap.parse_args(argv)
    root = args.repo_root.resolve()
    config = args.config or root / "site" / "site.json"
    prose = args.cells or root / "site" / "cells.json"
    out = args.out or root / "docs"
    readme_out = args.readme_out or root / "site" / "README_header.md"
    readme = None if str(args.readme) == "none" else (args.readme or root / "README.md")
    dfolder = None if str(args.data_folder) == "none" else (args.data_folder or root / "dist" / "data-folder")
    check = args.check or args.check_only
    try:
        cfg = load_config(config)
        data = load_data(root, prose, cfg)
        print("config: %s (github_owner=%s, data_folder_url=%s, data_base_url=%s, doi=%s)"
              % (config, json.dumps(cfg["github_owner"]), json.dumps(cfg["data_folder_url"]),
                 json.dumps(cfg["data_base_url"]), json.dumps(cfg["doi"])))
        print("data: %d cells, %d other hosted files and %d intermediates from results/cells.tsv; "
              "commands from cells/*/build.sh, cells/*/decode.sh and scripts/intermediates.sh"
              % (len(data["cells"]), len(data["files"]), len(data["intermediates"])))
        site = Site(cfg, data)
        files, dfiles = render_all(site, out, readme_out, readme, dfolder, HERE / "style.css")
        stale = stale_pages(out, files)
        nstale = 0
        if check:
            for p, text in files.items():
                cur = p.read_text(encoding="utf-8") if p.exists() else None
                if cur != text:
                    nstale += 1
                    print("out of date: %s" % p)
            for p in stale:
                nstale += 1
                print("out of date: %s (no longer generated)" % p)
            print("%d of %d site outputs out of date" % (nstale, len(files)))
        else:
            for p, text in list(files.items()) + list(dfiles.items()):
                write_text(p, text)
            for p in stale:
                p.unlink()
                print("removed stale generated page %s" % p)
            print("wrote %d pages and the assets to %s" % (sum(1 for p in files if p.suffix == ".html"), out))
            print("wrote %s%s" % (readme_out, " and its block in %s" % readme if readme and Path(readme).exists() else ""))
            if dfiles:
                print("wrote %d data folder files to %s" % (len(dfiles), dfolder))
        named = site.L.repo_paths | named_repo_paths(cfg, data)
        hosted = [c["file"] for c in data["cells"] if c["hosted"]] + [x["file"] for x in data["files"]]
        data_files = hosted + list(cfg.get("data_index_files", []))
        problems, report = check_site(out, cfg, data["facts"]["text_url"], readme_out, root, named, data_files,
                                      readme_full=readme)
        if dfiles:
            sums = root / "SHA256SUMS"
            rel = {p.relative_to(dfolder): t for p, t in dfiles.items()}
            problems += check_data_folder(rel, cfg, data["facts"]["text_url"], set(data_files),
                                          sums.read_text(encoding="utf-8") if sums.exists() else None)
            report.append("data folder: %d files checked (structure, links, SHA256SUMS equal to the repository's)" % len(dfiles))
    except BuildError as e:
        print("build_site: error: %s" % e, file=sys.stderr)
        return 2
    for line in report:
        print("check: " + line)
    for p in problems:
        print("PROBLEM: " + p)
    print("check: %d problems" % len(problems))
    return 1 if problems or nstale else 0


if __name__ == "__main__":
    sys.exit(main())
