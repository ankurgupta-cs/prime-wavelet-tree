def parse_threads(text):
    """'1' -> {'all': 1}; 'as run: extraction 15, search 6, encode 4' -> by step."""
    if re.match(r"^\d+$", text):
        return {"all": int(text)}
    m = dict((k, int(v)) for k, v in re.findall(r"([a-z]+) (\d+)", text))
    if not m:
        raise BuildError("cannot read build_threads %r" % text)
    return m


def load_data(root, prose_path, cfg):
    """Everything the pages print: numbers, files and URLs from results/cells.tsv,
    commands from the scripts, prose from site/cells.json."""
    try:
        prose = json.loads(Path(prose_path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise BuildError("cannot read %s: %s" % (prose_path, e))
    rows = read_tsv(root / "results" / "cells.tsv")
    by = {}
    for r in rows:
        if r["tag"] in by:
            raise BuildError("results/cells.tsv: tag %s twice" % r["tag"])
        by[r["tag"]] = r
    tf = {r["tag"]: r["value"] for r in rows if r["kind"] == "fact"}
    for k in FACTS_NEEDED:
        if k not in tf:
            raise BuildError("results/cells.tsv lacks the fact %s" % k)
    for t in CELL_ORDER + ["oracle", "text"]:
        if t not in by:
            raise BuildError("results/cells.tsv lacks the row %s" % t)
    inter_man = read_manifest(root / "results" / "INTERMEDIATES")
    N = int(tf["count"])
    oracle, text = by["oracle"], by["text"]
    for r in rows:
        if r["kind"] in ("cell", "reference") and r["sha256"] != "-" and not SHA_RE.match(r["sha256"]):
            raise BuildError("results/cells.tsv: %s sha256 is not a SHA-256" % r["tag"])

    # the cells
    cells = []
    for tag in CELL_ORDER:
        r, p = by[tag], prose["cells"].get(tag)
        if p is None:
            raise BuildError("site/cells.json has no prose for cell %s" % tag)
        c = {"tag": tag, "dir": r["dir"], "switches": r["switches"], "table_row": r["table_row"],
             "title": p["title"], "stores": p["stores"], "format": p["format"],
             "contents": p.get("contents"), "rebuilt_from": p.get("rebuilt_from"),
             "file": r["file"], "hosted": r["hosted"] == "yes", "url": r["url"] if r["hosted"] == "yes" else None,
             "bytes": int(r["bytes"]), "bits_printed": r["bits_printed"], "sha256": r["sha256"],
             "build_min": r["build_min"], "build_threads": parse_threads(r["build_threads"]),
             "build_as_run": r["build_threads"].startswith("as run"),
             "decode_cns_min": r["decode_cns_min"], "decode_list_only_min": none_if_dash(r["decode_list_only_min"]),
             "decode_primes_min": r["decode_primes_min"],
             "certify": {"s": r["certify_s"], "threads": int(r["certify_threads"]), "date": r["certify_date"]},
             "ram_gb": r["ram_gb"], "disk_gb": r["disk_gb"],
             "rebuilt": tf["rebuild_date"] if SHA_RE.match(r["gate_sha256"]) else None,
             "build_extract_s": r["build_extract_s"], "build_search_s": none_if_dash(r["build_search_s"]),
             "build_encode_s": r["build_encode_s"]}
        cmd = cell_commands(root, c, oracle["file"], inter_man)
        c["routes"], c["default_route"], c["decode"] = cmd["routes"], cmd["default_route"], cmd["decode"]
        # the route the published build took: the search route when there was a search
        asrun = "search" if c["build_search_s"] and "search" in c["routes"] else c["default_route"]
        c["asrun_inputs"] = c["routes"][asrun]["inputs"]
        c["inputs"] = c["routes"][c["default_route"]]["inputs"]
        cells.append(c)

    # intermediates: the ones scripts/intermediates.sh builds; time from the cell that builds only it
    icmd = intermediate_commands(root, oracle["file"], inter_man)
    inter = []
    for key, command in icmd.items():
        r = by.get(key)
        p = prose["intermediates"].get(key)
        if r is None or p is None:
            raise BuildError("intermediate %s: no row in results/cells.tsv or no prose in site/cells.json" % key)
        src = [c for c in cells if c["inputs"] == [key] and c["build_threads"] == {"all": 1}]
        if not src:
            raise BuildError("no one-thread cell build times the intermediate %s" % key)
        inter.append({"key": key, "name": p["name"], "what": p["what"], "file": r["file"],
                      "bytes": int(r["bytes"]), "sha256": r["sha256"], "command": command,
                      "s": src[0]["build_extract_s"], "threads": 1})

    # other hosted files (the oracle)
    files = []
    for r in rows:
        if r["kind"] == "cell" or r["hosted"] != "yes":
            continue
        p = prose["files"].get(r["tag"])
        if p is None:
            raise BuildError("site/cells.json has no prose for the hosted file %s" % r["tag"])
        files.append({"key": r["tag"], "file": r["file"], "format": p["format"], "bytes": int(r["bytes"]),
                      "sha256": r["sha256"], "url": r["url"], "what": p["what"], "contents": p.get("contents"),
                      "bits_printed": r["bits_printed"]})

    # the rows of the results table, from table_row and the C switch
    rows_out, seen = [], {}
    for c in cells:
        key = c["table_row"]
        if key not in seen:
            seen[key] = {"key": key, "label": prose["row_labels"].get(key, key), "cells": [None, None]}
            rows_out.append(seen[key])
        half = int(c["switches"][2])
        if seen[key]["cells"][half] is not None:
            raise BuildError("two cells in row %s, half %d" % (key, half))
        seen[key]["cells"][half] = c["tag"]
    for rr in rows_out:
        if rr["cells"][0] is None:
            rr["mark"] = "ddagger"

    # facts: from the TSV, plus values derived from it for the prose
    def fx(x, p):
        return fixed(x, p)
    hosted_cells = [c for c in cells if c["hosted"]]
    one = [c for c in cells if c["certify"]["threads"] == 1]
    many = [c for c in cells if c["certify"]["threads"] != 1]
    one_build = [c for c in cells if c["build_threads"] == {"all": 1}]
    dstar = by["111x"]
    paths_bytes = int(by["dstar_paths"]["bytes"]) if "dstar_paths" in by else None
    facts = {
        "count": N, "bound": prose["bound"], "prefix_bound": prose["prefix_bound"],
        "prefix_cns": int(tf["prefix_count"]),
        "text_bytes": int(text["bytes"]), "text_sha256": text["sha256"], "text_url": text["url"],
        "text_file": text["file"], "text_gb": fx(Decimal(text["bytes"]) / 10 ** 9, 2),
        "oracle_gb": fx(Decimal(oracle["bytes"]) / 10 ** 9, 2),
        "machine": tf["machine"], "compiler": tf["compiler"],
        "load_s_min": tf["load_s_min"], "load_s_max": tf["load_s_max"], "sort_min": tf["sort_min"],
        "factor_sample_block": int(tf["factor_sample_stride"]), "factor_block_size": int(tf["oracle_block_cns"]),
        "factor_sample_cns": int(tf["factor_sample"]), "rebuild_date": tf["rebuild_date"],
        "hosted_cell_gb_min": fx(Decimal(min(c["bytes"] for c in hosted_cells)) / 10 ** 9, 2),
        "hosted_cell_gb_max": fx(Decimal(max(c["bytes"] for c in hosted_cells)) / 10 ** 9, 2),
        "certify_one_lo": fx(min(dec(c["certify"]["s"]) for c in one) / 60, 1),
        "certify_one_hi": fx(max(dec(c["certify"]["s"]) for c in one) / 60, 1),
        "certify_many_lo": fx(min(dec(c["certify"]["s"]) for c in many) / 60, 1) if many else "-",
        "certify_many_hi": fx(max(dec(c["certify"]["s"]) for c in many) / 60, 1) if many else "-",
        "certify_many_threads": ", ".join(sorted({str(c["certify"]["threads"]) for c in many})) or "-",
        "build_one_lo": min((c["build_min"] for c in one_build), key=dec),
        "build_one_hi": max((c["build_min"] for c in one_build), key=dec),
        "build_ram_gb": fx(max(dec(c["ram_gb"]) for c in one_build), 0),
        "build_disk_gb": max((c["disk_gb"] for c in one_build), key=dec),
        "intermediates_gb": fx(Decimal(sum(x["bytes"] for x in inter)) / 10 ** 9, 0),
        "oracle_build_min": oracle["build_min"],
        "oracle_disk_gb": fx(Decimal(2 * int(text["bytes"]) + int(oracle["bytes"])) / 10 ** 9, 0),
        "search_h": fx(dec(dstar["build_search_s"]) / 3600, 1),
        "search_threads": parse_threads(dstar["build_threads"]).get("search", 1),
        "search_ram_gb": fx(dec(dstar["ram_gb"]), 0),
        "dstar_export_min": fx(dec(tf["dstar_export_s"]) / 60, 1),
        "dstar_reencode_min": fx(dec(tf["dstar_reencode_s"]) / 60, 1),
        "dstar_rebuild_min": fx((dec(tf["dstar_export_s"]) + dec(tf["dstar_reencode_s"])) / 60, 0),
        "dstar_paths_gb": fx(Decimal(paths_bytes) / 10 ** 9, 1) if paths_bytes else "-",
    }
    data = {"facts": facts, "rows": rows_out, "cells": cells, "files": files, "intermediates": inter,
            "formats": prose["formats"], "tiers": prose["tiers"], "oracle_file": oracle["file"]}
    validate_data(data, cfg)
    return data


def validate_data(d, cfg):
    f = d["facts"]
    if not SHA_RE.match(f["text_sha256"]):
        raise BuildError("the text's sha256 is not a SHA-256")
    validate_url("text url (results/cells.tsv)", f["text_url"])
    fmt_keys = {x["key"] for x in d["formats"]}
    n = Decimal(f["count"])
    for c in d["cells"]:
        if not re.match(r"^[0-9a-z]+$", c["tag"]) or not re.match(r"^[01]{3}$", c["switches"]):
            raise BuildError("cell %s: bad tag or switches %r" % (c["tag"], c["switches"]))
        if not SHA_RE.match(c["sha256"]):
            raise BuildError("cell %s: sha256 is not a full SHA-256" % c["tag"])
        if c["format"] not in fmt_keys:
            raise BuildError("cell %s: unknown format %s" % (c["tag"], c["format"]))
        got = fixed(Decimal(c["bytes"]) * 8 / n, 2)
        if got != c["bits_printed"]:
            raise BuildError("cell %s: bits_printed %s, but its bytes give %s" % (c["tag"], c["bits_printed"], got))
        for k in ("build_min", "decode_cns_min", "decode_primes_min"):
            try:
                dec(c[k])
            except Exception:
                raise BuildError("cell %s: %s=%r is not a number" % (c["tag"], k, c[k]))
        if c["hosted"] and cfg["data_base_url"] and c["url"] != cfg["data_base_url"] + "/" + c["file"]:
            raise BuildError("cell %s: url %s in results/cells.tsv is not data_base_url + file name"
                             % (c["tag"], c["url"]))
        if c["hosted"] and c["contents"] is None:
            raise BuildError("cell %s is hosted but has no contents line in site/cells.json" % c["tag"])
    for x in d["files"]:
        if not SHA_RE.match(x["sha256"]) or x["format"] not in fmt_keys:
            raise BuildError("file %s: bad sha256 or format" % x["key"])
        if cfg["data_base_url"] and x["url"] != cfg["data_base_url"] + "/" + x["file"]:
            raise BuildError("file %s: url %s in results/cells.tsv is not data_base_url + file name" % (x["key"], x["url"]))
    for x in d["intermediates"]:
        if not SHA_RE.match(x["sha256"]):
            raise BuildError("intermediate %s: bad sha256" % x["key"])


def named_repo_paths(cfg, data):
    """Repository paths the site names: specifications and cell folders."""
    rp = cfg.get("repo_paths", {})
    paths = set(rp.get("specs", {}).values())
    for c in data["cells"]:
        paths.add("%s/%s" % (rp.get("cells_dir", "cells"), c["dir"]))
    return paths


