    def results_table(self, root):
        cells = [self.cells[t] for t in self.order]
        best = {
            "bits": min(dec(c["_bits"]) for c in cells),
            "build": min(dec(c["build_min"]) for c in cells),
            "dec": min(dec(c["decode_cns_min"]) for c in cells),
            "pri": min(dec(c["decode_primes_min"]) for c in cells),
        }

        def td(c, cls, value, key, mark=""):
            v = self.dnum(value, mark)
            if dec(value) == best[key]:
                v = "<strong>%s</strong>" % v
            dark = " dk" if c is self.head else ""
            return '<td class="num %s%s">%s</td>' % (cls, dark, v)

        head2 = ('<th scope="col" class="tagcol">Cell</th>'
                 '<th scope="col" class="sp">Space <span class="unit">(bits per CN)</span></th>'
                 '<th scope="col" class="bd">Build <span class="unit">(min)</span></th>'
                 '<th scope="col" class="dc">Decode, CNs only <span class="unit">(min)</span></th>'
                 '<th scope="col" class="dc">Decode, CNs + primes <span class="unit">(min)</span></th>'
                 '<th scope="col" class="avail">Get the file</th>')
        caption = ("The eight cells and the %s row, on all %s Carmichael numbers (CNs) below %s."
                   % (self.t.html("{dstar}"), commas(self.f["count"]), self.t.html(self.f["bound"])))
        out = ['<div class="table-wrap" role="region" aria-labelledby="abc-caption" tabindex="0">',
               '<table class="abc">',
               '<caption id="abc-caption">%s</caption>' % caption,
               '<colgroup><col></colgroup><colgroup span="6"></colgroup><colgroup span="6"></colgroup>',
               "<thead>",
               '<tr><th scope="col" rowspan="2" class="rowhead">Stores</th>'
               '<th scope="colgroup" colspan="6" class="half">Byte-aligned (C = 0)</th>'
               '<th scope="colgroup" colspan="6" class="half">Coded (C = 1)</th></tr>',
               "<tr>%s%s</tr>" % (head2, head2.replace('class="tagcol"', 'class="tagcol half"')),
               "</thead>", "<tbody>"]
        for r in self.d["rows"]:
            mark = "‡" if r.get("mark") == "ddagger" else ""
            label = self.t.html(r["label"]) + ('<sup class="mk">%s</sup>' % mark if mark else "")
            cls = ' class="sep"' if mark else ""
            row = ['<tr%s><th scope="row">%s</th>' % (cls, label)]
            for i, tag in enumerate(r["cells"]):
                half = " half" if i == 1 else ""
                if tag is None:
                    row.append('<td class="blank%s" colspan="6"></td>' % half)
                    continue
                c = self.cells[tag]
                row.append('<td class="tag%s"><a href="%s">%s</a></td>' % (half, esc(self.cell_href(root, tag)), esc(tag)))
                row.append(td(c, "sp", c["_bits"], "bits"))
                row.append(td(c, "bd", c["build_min"], "build", "§" if c.get("build_as_run") else ""))
                row.append(td(c, "dc", c["decode_cns_min"], "dec", "†" if c.get("decode_list_only_min") else ""))
                row.append(td(c, "dc", c["decode_primes_min"], "pri"))
                if c["hosted"]:
                    row.append('<td class="avail"><a href="%sdata.html#file-%s" aria-label="Download details for cell %s">download</a></td>'
                               % (root, esc(tag), esc(tag)))
                else:
                    row.append('<td class="avail"><a href="%s" aria-label="How to rebuild cell %s">rebuild</a></td>'
                               % (esc(self.cell_href(root, tag, "build")), esc(tag)))
            row.append("</tr>")
            out.append("".join(row))
        out += ["</tbody>", "</table>", "</div>"]
        return "\n".join(out) + "\n" + self.table_notes()

