    def bibtex(self):
        p = self.cfg["paper"]
        fields = [("title", "{%s}" % p["bibtex_title"]),
                  ("author", "{%s}" % " and ".join(x["bibtex"] for x in p["authors"])),
                  ("year", "{%s}" % p["year"])]
        if self.cfg["arxiv_id"]:
            fields += [("eprint", "{%s}" % self.cfg["arxiv_id"]), ("archivePrefix", "{arXiv}")]
            if self.cfg.get("arxiv_primary_class"):
                fields.append(("primaryClass", "{%s}" % self.cfg["arxiv_primary_class"]))
        if self.cfg["doi"]:
            fields.append(("doi", "{%s}" % self.cfg["doi"]))
        if p.get("venue_note"):
            fields.append(("note", "{%s}" % p["venue_note"].rstrip(".")))
        w = max(len(k) for k, _ in fields)
        lines = ["@misc{%s," % p["bibtex_key"]]
        lines += ["  %s = %s," % (k.ljust(w), v) for k, v in fields]
        lines[-1] = lines[-1].rstrip(",")
        lines.append("}")
        return lines

