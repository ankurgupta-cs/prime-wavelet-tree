# ------------------------------------------------------------------ commands from the scripts

RUN_RE = re.compile(r'(\$\()?run\s+"\$\(tool ([A-Za-z0-9_]+)\)"(.*)$')
INTER_RE = re.compile(r'bash\s+"\$ROOT/scripts/intermediates\.sh"\s+([a-z_ ]+?)\s*(?:\|\||$)')
ASSIGN_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")
CASE_RE = re.compile(r"^case\s+\$\{?(\w+)\}?\s+in$")
BRANCH_RE = re.compile(r"^([A-Za-z0-9_|*]+)\)\s*(.*)$")
IF_RE = re.compile(r'^if\s+\[\s+"\$\{(\w+):-([^}]*)\}"\s+=\s+"?([^"\s]+)"?\s+\];\s*then$')
VAR_RE = re.compile(r"\$\{(\w+)(?::-([^}]*))?\}|\$(\w+)")


class Script:
    """The statements of a cell or driver script that matter for the site: the
    tools it runs (run "$(tool X)" ...), the intermediates it builds, and the
    variable assignments, each tagged with its case branch and if-condition."""

    def __init__(self, path):
        self.path = Path(path)
        try:
            raw = self.path.read_text(encoding="utf-8").splitlines()
        except OSError as e:
            raise BuildError("cannot read %s: %s" % (path, e))
        lines, buf = [], ""
        for ln in raw:                                  # join continuation lines
            if ln.rstrip().endswith("\\"):
                buf += ln.rstrip()[:-1] + " "
                continue
            lines.append(buf + ln)
            buf = ""
        self.items = []                                 # (kind, branch, cond, payload)
        self.vars = {None: {}}                          # branch -> {name: value}
        self.case_var = None
        branch, cond, in_case = None, None, False
        for ln in lines:
            s = ln.strip()
            if not s or s.startswith("#"):
                continue
            m = CASE_RE.match(s)
            if m and not in_case:
                in_case, self.case_var = True, m.group(1)
                continue
            if s.startswith("esac"):
                in_case, branch = False, None
                continue
            if in_case:
                m = BRANCH_RE.match(s)
                if m and branch is None:
                    branch = m.group(1)
                    self.vars.setdefault(branch, {})
                    s = m.group(2).strip()
            ends = s.endswith(";;")
            if ends:
                s = s[:-2].strip()
            m = IF_RE.match(s)
            if m:
                var, default, value = m.groups()
                cond = ("then", var, default, value)
            elif s == "else" and cond:
                cond = ("else",) + cond[1:]
            elif s.startswith("fi") and cond:
                cond = None
            else:
                self._statement(s, branch, cond)
            if ends:
                branch, cond = None, None

    def _statement(self, s, branch, cond):
        m = RUN_RE.search(s)
        if m:
            inside, tool, rest = m.groups()
            rest = rest.split(" || ", 1)[0].rstrip()
            if inside:                              # out=$(run ...) : drop the closing parenthesis
                if not rest.endswith(")"):
                    raise BuildError("%s: cannot read %r" % (self.path, s))
                rest = rest[:-1]
            self.items.append(("run", branch, cond, tool + rest))
            return
        m = INTER_RE.search(s)
        if m:
            self.items.append(("inter", branch, cond, m.group(1).split()))
            return
        m = ASSIGN_RE.match(s)
        if m and not s.startswith(("local ", "export ")):
            name, value = m.groups()
            if value.startswith('"') and value.endswith('"') and len(value) >= 2:
                value = value[1:-1]
            d = re.match(r"^\$\{%s:-(.*)\}$" % re.escape(name), value)
            if d:                                   # X=${X:-default}: the default
                value = d.group(1)
            self.vars.setdefault(branch, {})[name] = value

    def branches(self):
        return [b for b in self.vars if b is not None and b != "*"]

    def default_branch(self):
        """The branch a case over $VAR takes when VAR is unset (from VAR=${VAR:-x})."""
        if self.case_var is None:
            return None
        return self.vars[None].get(self.case_var)

    def select(self, branch):
        """Items and variables of the top level plus one branch, in script order."""
        env = dict(self.vars[None])
        if branch is not None:
            env.update(self.vars.get(branch, {}))
        items = [it for it in self.items if it[1] is None or it[1] == branch]
        return items, env


class Resolver:
    """Expands the shell variables of a command the way the make targets run it,
    with the default directories (data/, work/) and N for THREADS."""

    def __init__(self, fixed_env, manifests):
        self.fixed = fixed_env          # values that win over the script's own assignments
        self.manifests = manifests      # "$CELL" / "$M" -> dict

    def expand(self, s, env, depth=0):
        if depth > 12:
            raise BuildError("variables nest too deep in %r" % s)

        def mget(m):
            man = self.manifests.get(m.group(1))
            if man is None or m.group(2) not in man:
                raise BuildError("cannot resolve $(mget \"$%s\" %s)" % (m.group(1), m.group(2)))
            return man[m.group(2)]
        s = re.sub(r'\$\(mget "\$(\w+)" "?([\w.]+)"?\)', mget, s)
        s = re.sub(r'"?\$\(tool (\w+)\)"?', r"\1", s)

        def var(m):
            name, default = (m.group(1), m.group(2)) if m.group(1) else (m.group(3), None)
            if name in self.fixed:
                return self.fixed[name]
            if name in env:
                return self.expand(env[name], env, depth + 1)
            if default is not None:
                return self.expand(default, env, depth + 1)
            raise BuildError("cannot resolve $%s" % name)
        return VAR_RE.sub(var, s)

    def command(self, s, env):
        out = self.expand(s, env)
        try:
            words = shlex.split(out)
        except ValueError as e:
            raise BuildError("cannot split %r: %s" % (out, e))
        line = " ".join(words)
        if "$" in line or "`" in line:
            raise BuildError("unresolved shell syntax left in %r" % line)
        return line


def cond_note(cond):
    """'' for the default side of an if over ${VAR:-default}, else 'with VAR=value'."""
    if cond is None:
        return ""
    side, var, default, value = cond
    then_is_default = default == value
    if (side == "then") == then_is_default:
        return ""
    return "with %s=%s" % (var, value) if side == "then" else "with %s other than %s" % (var, value)


def cell_commands(root, cell, oracle_file, inter_man):
    """Build routes, inputs and decode commands of a cell, from its scripts."""
    d = root / "cells" / cell["dir"]
    man = read_manifest(d / "CELL")
    if man.get("file") != cell["file"] or man.get("sha256") != cell["sha256"]:
        raise BuildError("cells/%s/CELL is out of date (run make table)" % cell["dir"])
    loc = "data/" if cell["hosted"] else "work/"
    fixed_env = {"WORK": "work", "DATA": "data", "ORC1": "data/" + oracle_file, "THREADS": "N",
                 "tag": cell["tag"], "F": loc + cell["file"]}
    R = Resolver(fixed_env, {"CELL": man, "M": inter_man})
    build = Script(d / "build.sh")
    routes = {}
    names = build.branches() or [None]
    for b in names:
        items, env = build.select(b)
        routes[b] = {
            "inputs": [n for k, _, _, p in items if k == "inter" for n in p],
            "commands": [R.command(p, env) for k, _, _, p in items if k == "run"],
        }
    default = build.default_branch()
    if default not in routes:
        raise BuildError("cells/%s/build.sh: default route %r not found" % (cell["dir"], default))
    decode = Script(d / "decode.sh")
    modes = {}
    for b in decode.branches():
        items, env = decode.select(b)
        runs = [(R.command(p, env), cond_note(c)) for k, br, c, p in items if k == "run" and br == b]
        runs.sort(key=lambda x: x[1] != "")      # the default first
        if runs:
            modes[b] = runs
    for need in ("verify", "certify"):
        if need not in modes:
            raise BuildError("cells/%s/decode.sh has no %s commands" % (cell["dir"], need))
    return {"routes": routes, "default_route": default, "decode": modes}


def intermediate_commands(root, oracle_file, inter_man):
    """The build rule of each intermediate, from scripts/intermediates.sh."""
    sc = Script(root / "scripts" / "intermediates.sh")
    out = {}
    for b in sc.branches():
        name = inter_man.get(b + ".file")
        if not name:
            raise BuildError("scripts/intermediates.sh builds %s, which results/INTERMEDIATES lacks" % b)
        R = Resolver({"ORC1": "data/" + oracle_file, "THREADS": "N", "WORK": "work",
                      "part": "work/" + name, "out": "work/" + name}, {"M": inter_man})
        items, env = sc.select(b)
        cmds = [R.command(p, env) for k, br, _, p in items if k == "run" and br == b]
        if len(cmds) != 1:
            raise BuildError("scripts/intermediates.sh: %d commands for %s" % (len(cmds), b))
        out[b] = cmds[0]
    return out


