def read_tsv(path):
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError as e:
        raise BuildError("cannot read %s: %s" % (path, e))
    lines = [ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]
    rows = list(csv.reader(lines, delimiter="\t", quoting=csv.QUOTE_NONE))
    if not rows:
        raise BuildError("%s has no header" % path)
    head = rows[0]
    missing = sorted(set(TSV_FIELDS.values()) - set(head))
    if missing:
        raise BuildError("%s lacks the columns %s (update TSV_FIELDS in build_site.py)" % (path, ", ".join(missing)))
    out = []
    for r in rows[1:]:
        if len(r) != len(head):
            raise BuildError("%s: row %r has %d fields, the header %d" % (path, r[0], len(r), len(head)))
        row = dict(zip(head, r))
        out.append({f: row[c] for f, c in TSV_FIELDS.items()})
    return out


def read_manifest(path):
    """key = value lines (cells/<dir>/CELL, results/INTERMEDIATES)."""
    out = {}
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError as e:
        raise BuildError("cannot read %s: %s" % (path, e))
    for ln in text.splitlines():
        if ln.lstrip().startswith("#") or "=" not in ln:
            continue
        k, _, v = ln.partition("=")
        out[k.strip()] = v.strip()
    return out


