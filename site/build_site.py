def validate_url(name, url):
    """An https URL with a lower-case host and no query, fragment, user or port.
    Plain http is refused: browsers block or warn on http downloads started from
    an https page, and GitHub Pages serves this site over https."""
    if not isinstance(url, str) or not url or url != url.strip() or re.search(r"\s", url):
        raise BuildError("%s: not a URL: %r" % (name, url))
    p = urlsplit(url)
    if p.scheme != "https" or not p.hostname:
        raise BuildError("%s: needs an https URL with a host: %r" % (name, url))
    if re.search(r'["<>\\^`{|}]', url):
        raise BuildError("%s: characters that need escaping in a URL: %r" % (name, url))
    if p.query or p.fragment or p.username or p.port is not None:
        raise BuildError("%s: no query, fragment, user or port allowed: %r" % (name, url))
    if p.netloc != p.netloc.lower():
        raise BuildError("%s: write the host in lower case: %r" % (name, url))


def load_config(path):
    try:
        cfg = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise BuildError("cannot read config %s: %s" % (path, e))
    need = ["github_owner", "repo_name", "branch", "data_folder_url", "data_base_url", "data_version",
            "arxiv_id", "doi", "table_credit", "table_credit_full", "table_paper", "paper",
            "code_licence", "code_licence_pending", "data_licence", "repo_paths", "make_targets",
            "repo_public"]
    missing = [k for k in need if k not in cfg]
    if missing:
        raise BuildError("config %s lacks keys: %s" % (path, ", ".join(missing)))
    for k in ("github_owner", "data_folder_url", "data_base_url", "arxiv_id", "doi", "code_licence", "data_licence"):
        if cfg.get(k) == "":
            raise BuildError("config %s: %s is an empty string; use null" % (path, k))
    if not isinstance(cfg["repo_public"], bool):
        raise BuildError("repo_public must be true or false: %r" % (cfg["repo_public"],))
    owner = cfg["github_owner"]
    if owner is not None and (not isinstance(owner, str) or not GH_USER_RE.match(owner)):
        raise BuildError("github_owner is not a GitHub user name: %r" % (owner,))
    if not isinstance(cfg["repo_name"], str) or not REPO_RE.match(cfg["repo_name"]):
        raise BuildError("repo_name is not a repository name: %r" % (cfg["repo_name"],))
    if not re.match(r"^[A-Za-z0-9._/-]+$", str(cfg["branch"])):
        raise BuildError("branch is not a branch name: %r" % (cfg["branch"],))
    if not re.match(r"^[a-z0-9._-]+$", str(cfg["data_version"])):
        raise BuildError("data_version is not a folder name: %r" % (cfg["data_version"],))
    if cfg["data_folder_url"] is not None:
        validate_url("data_folder_url", cfg["data_folder_url"])
        if not cfg["data_folder_url"].endswith("/"):
            raise BuildError("data_folder_url must end with '/': %r" % cfg["data_folder_url"])
    if cfg["data_base_url"] is not None:
        validate_url("data_base_url", cfg["data_base_url"])
        cfg["data_base_url"] = cfg["data_base_url"].rstrip("/")
        if cfg["data_folder_url"] is None:
            raise BuildError("data_base_url is set but data_folder_url is null")
        if cfg["data_base_url"] != cfg["data_folder_url"] + cfg["data_version"]:
            raise BuildError("data_base_url %r is not data_folder_url + data_version (%r)"
                             % (cfg["data_base_url"], cfg["data_folder_url"] + cfg["data_version"]))
    if cfg["arxiv_id"] is not None and not ARXIV_RE.match(str(cfg["arxiv_id"])):
        raise BuildError("arxiv_id is not an arXiv identifier: %r" % (cfg["arxiv_id"],))
    if not ARXIV_RE.match(str(cfg["table_paper"].get("arxiv_id", ""))):
        raise BuildError("table_paper.arxiv_id is not an arXiv identifier")
    if cfg["doi"] is not None and not DOI_RE.match(str(cfg["doi"])):
        raise BuildError("doi is not a DOI: %r" % (cfg["doi"],))
    for k in ("code_licence", "data_licence"):
        if cfg[k] is not None and cfg[k] not in LICENCES:
            raise BuildError("%s: unknown licence %r (known: %s)" % (k, cfg[k], ", ".join(sorted(LICENCES))))
    for k in ("title", "authors", "year", "affiliation", "venue_note", "bibtex_key", "bibtex_title"):
        if k not in cfg["paper"]:
            raise BuildError("paper lacks %s" % k)
    for k in ("check", "fetch", "verify", "certify", "rebuild", "fetch_oracle", "rebuild_oracle", "dstar_search"):
        if k not in cfg["make_targets"]:
            raise BuildError("make_targets lacks %s" % k)
    return cfg


class Links:
    """Every URL the site prints. A method returns None when its config value is null."""

    def __init__(self, cfg, text_url):
        self.cfg = cfg
        self.owner = cfg["github_owner"]
        self.repo = cfg["repo_name"]
        self.branch = cfg["branch"]
        self.folder = cfg["data_folder_url"]
        self.data = cfg["data_base_url"]
        self._text_url = text_url
        self.repo_paths = set()       # every repository path the site names, linked or not

    def repo_url(self):
        return "https://github.com/%s/%s" % (self.owner, self.repo) if self.owner else None

    def clone_url(self):
        return self.repo_url() + ".git" if self.owner else None

    def site_url(self):
        return "https://%s.github.io/%s/" % (self.owner.lower(), self.repo) if self.owner else None

    def site_anchor(self, page, anchor):
        base = self.site_url()
        return None if base is None else base + page + "#" + anchor

    def blob(self, path):
        self.repo_paths.add(path)
        if not self.owner:
            return None
        return "%s/blob/%s/%s" % (self.repo_url(), self.branch, quote(path))

    def tree(self, path):
        self.repo_paths.add(path)
        if not self.owner:
            return None
        return "%s/tree/%s/%s" % (self.repo_url(), self.branch, quote(path))

    def data_folder(self):
        """The data directory the paper cites (the top-line Data link)."""
        return self.folder

    def data_dir(self):
        """The folder of this version's files."""
        return self.data + "/" if self.data else None

    def data_file(self, name):
        return "%s/%s" % (self.data, quote(name)) if self.data else None

    def arxiv_abs(self):
        a_id = self.cfg["arxiv_id"]
        return "https://arxiv.org/abs/" + a_id if a_id else None

    def table_arxiv(self):
        return "https://arxiv.org/abs/" + self.cfg["table_paper"]["arxiv_id"]

    def doi_url(self):
        d = self.cfg["doi"]
        # parentheses and other DOI characters are percent-encoded so the link survives Markdown
        return "https://doi.org/" + quote(d, safe="/:;._-") if d else None

    def text_url(self):
        return self._text_url

    def licence_url(self, key):
        spdx = self.cfg[key]
        return LICENCES[spdx][1] if spdx else None

    def allowed(self):
        """host -> schemes allowed for it; only hosts the config and the TSV name."""
        hosts = {}

        def add(url):
            p = urlsplit(url)
            hosts.setdefault(p.hostname, set()).add(p.scheme)
        add(self.text_url())
        add("https://arxiv.org/")
        if self.owner:
            add("https://github.com/")
            add(self.site_url())
        if self.folder:
            add(self.folder)
        if self.cfg["doi"]:
            add("https://doi.org/")
        for k in ("code_licence", "data_licence"):
            if self.cfg[k]:
                add(self.licence_url(k))
        return hosts


def a(url, text_html, label=None):
    """A link, or the text with a pending marker when the URL is not known yet."""
    if url is None:
        return '%s <span class="pending">(%s)</span>' % (text_html, esc(PENDING))
    extra = ' aria-label="%s"' % esc(label) if label else ""
    return '<a href="%s"%s>%s</a>' % (esc(url), extra, text_html)


def md_link(url, text):
    if url is None:
        return "%s *(%s)*" % (text, PENDING)
    return "[%s](%s)" % (text, url)


