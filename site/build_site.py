def esc(s):
    return html.escape(str(s), quote=True)


def dec(x):
    """Decimal from a number or a string such as '2,011'."""
    return Decimal(str(x).replace(",", ""))


def fixed(x, places):
    """Round half up to a fixed number of decimal places."""
    q = Decimal(1).scaleb(-places) if places else Decimal(1)
    return str(dec(x).quantize(q, rounding=ROUND_HALF_UP))


def group(s):
    """Thousands separators on the integer part of a decimal string."""
    s = str(s).replace(",", "")
    ip, _, fp = s.partition(".")
    return "{:,}".format(int(ip)) + ("." + fp if fp else "")


def commas(n):
    return "{:,}".format(int(n))


def duration(seconds):
    """Seconds as minutes, or as hours from ten hours up."""
    m = dec(seconds) / 60
    if m >= 600:
        return fixed(m / 60, 1) + " h"
    if m < 1:
        return fixed(m, 2) + " min"
    return group(fixed(m, 1)) + " min"


def threads_text(t):
    return "one thread" if int(t) == 1 else "%d threads" % int(t)


def join_and(parts):
    if len(parts) <= 1:
        return "".join(parts)
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def gb(nbytes):
    return fixed(Decimal(nbytes) / Decimal(10) ** 9, 2) + " GB"


def bare(url):
    """A URL without its scheme and trailing slash, for link text."""
    return re.sub(r"^https?://", "", url).rstrip("/")


# ------------------------------------------------------------------ markup

TOKENS = {
    "{n}": ("<i>n</i>", "n"),
    "{d}": ("<i>d</i>", "d"),
    "{dmin}": ("<i>d</i><sub>min</sub>", "d_min"),
    "{dstar}": ("<i>d</i><sup>∗</sup>", "d*"),
    "{rstar}": ("<i>r</i><sup>⋆</sup>", "r*"),
    "{lambda}": ("<i>λ</i>", "λ"),
}
FACT_RE = re.compile(r"\{fact:([a-z_0-9]+)\}")
POW_RE = re.compile(r"\^(-?\d+)")


class Text:
    """The markup of cells.json: {n} {d} {dmin} {dstar} {rstar} {lambda},
    powers such as 10^24, and {fact:key} for a value from facts."""

    def __init__(self, facts):
        self.facts = facts

    def _facts(self, s):
        def rep(m):
            k = m.group(1)
            if k not in self.facts:
                raise BuildError("unknown {fact:%s} in %r" % (k, s))
            v = self.facts[k]
            return commas(v) if isinstance(v, int) else str(v)
        return FACT_RE.sub(rep, s)

    def tok(self, h):
        """Expand the markup in a string that is already HTML."""
        for k, (rep, _) in TOKENS.items():
            h = h.replace(k, rep)
        h = POW_RE.sub(lambda m: "<sup>" + m.group(1).replace("-", "−") + "</sup>", h)
        if "{" in h or "}" in h:
            raise BuildError("unknown markup in %r" % h)
        return h

    def html(self, s):
        """Escape plain text from the data files, then expand its markup."""
        return self.tok(esc(self._facts(s)))

    def plain(self, s):
        out = self._facts(s)
        for k, (_, t) in TOKENS.items():
            out = out.replace(k, t)
        if "{" in out or "}" in out:
            raise BuildError("unknown markup in %r" % s)
        return out


